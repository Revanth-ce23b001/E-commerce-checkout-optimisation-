        naive=truth["planted_causal_effects"]["cod_on_rto"]["naive_observed_gap_pp"],
        selection=truth["planted_causal_effects"]["cod_on_rto"]["selection_share_of_naive_gap"],
        points=md_table(model.points().head(14)[["feature", "points_per_sd"]], "{:.2f}"),
