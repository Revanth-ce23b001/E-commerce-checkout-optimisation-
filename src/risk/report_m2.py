        reliability=md_table(evaluate.reliability(y_test, p_test)),
        slope=ctx["scoreboard"].iloc[-1]["cal_slope"],
        intercept=ctx["scoreboard"].iloc[-1]["cal_intercept"],
        ece=ctx["scoreboard"].iloc[-1]["ece"],
        brier=ctx["scoreboard"].iloc[-1]["brier"],
