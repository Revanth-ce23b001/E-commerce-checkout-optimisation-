"""The Phase 4 Stage-2 report writer — M2, under the A47 ruling.

One long markdown template plus the tables computed for the report alone. Like
``report.py`` it decides nothing; ``scripts/07_fit_m2.py`` does.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from . import evaluate, features, interventions, policy
from .challenger import SHIP_MARGIN_AUC
from .fairness import PROXY_RATIO_LIMIT
from .report import md_table

LK03_LIMIT = 0.85
FEASIBILITY_GATE = 0.72
MED_TIER_FLOOR = 0.10  # blueprint §8.3


def pstar_tiers(score: np.ndarray, pstar: float) -> pd.Series:
    """Blueprint §8.3's economically anchored tiers. Not percentiles."""
    return pd.Series(np.where(score >= pstar, "HIGH",
                              np.where(score >= MED_TIER_FLOOR, "MED", "LOW")))


def tier_table(score: np.ndarray, y: np.ndarray, pstar: float) -> pd.DataFrame:
    """Realised shares against §8.3's expected shares, which were priors."""
    tiers = pstar_tiers(score, pstar)
    expected = {"LOW": 45.0, "MED": 38.0, "HIGH": 17.0}
    rows = []
    for tier in ("LOW", "MED", "HIGH"):
        mask = (tiers == tier).to_numpy()
        rows.append({
            "tier": tier,
            "definition": {"LOW": f"p < {MED_TIER_FLOOR:.2f}",
                           "MED": f"{MED_TIER_FLOOR:.2f} <= p < {pstar:.4f}",
                           "HIGH": f"p >= {pstar:.4f} (p*)"}[tier],
            "orders": int(mask.sum()),
            "share_pct": round(float(mask.mean()) * 100, 2),
            "expected_share_pct": expected[tier],
            "observed_rto": round(float(np.asarray(y)[mask].mean()), 4) if mask.any() else np.nan,
        })
    return pd.DataFrame(rows)


def _show_ratio(audit: pd.DataFrame) -> pd.DataFrame:
    """Render `ratio` as text so a numeric column does not print at 4dp beside a
    string one. FA-01's own logic reads the numeric frame, never this."""
    out = audit.copy()
    out["ratio"] = out["ratio"].map(
        lambda v: f"{v:.2f}x" if isinstance(v, (int, float)) else v)
    return out


def _bars(auc: float, ceiling: float) -> str:
    rows = [
        ("Achievable AUC ceiling (`_truth.json`)", f"{ceiling:.4f}",
         "below" if auc < ceiling else "AT OR ABOVE — LEAK"),
        ("LK-03 hard limit", f"{LK03_LIMIT:.2f}", "PASS" if auc < LK03_LIMIT else "FAIL"),
        ("Feasibility gate (§9.4)", f"{FEASIBILITY_GATE:.2f}",
         "full risk-based pricing" if auc >= FEASIBILITY_GATE else "COARSE TIERS ONLY"),
    ]
    body = "\n".join(f"| {n} | {v} | {auc:.4f} | {s} |" for n, v, s in rows)
    return "| Bar | Value | M2 test | Status |\n|---|---|---|---|\n" + body


def write_report(ctx: dict, truth: dict, path) -> None:
    ceiling = truth["achieved"]["auc_ceiling_precheckout"]
    pstar = truth["economics_targets"]["breakeven_rto_probability_derived"]
    ann = truth["economics_targets"]["annualization_factor_derived"]

    split, model, p_test, y_test = ctx["split"], ctx["model"], ctx["p_test"], ctx["y_test"]
    test, cm, gbm = ctx["test"], ctx["cm"], ctx["gbm"]
    m2_auc = ctx["m2_auc"]

    coefs = model.coefficients()
    top = coefs[coefs["feature"] != "(intercept)"].head(20)[
        ["feature", "coef_per_sd", "odds_ratio_per_sd", "p_value"]]
    exclusions = pd.DataFrame(
        [{"column": k, "reason": v} for k, v in features.EXCLUSIONS.items()])

    audit_global = policy.ratio_audit(test, p_test, "global")
    audit_tiered = policy.ratio_audit(test, p_test, "per-tier")
    cost = policy.margin_cost(test, p_test, cm, ann)
    exposure_g = policy.tier_exposure(test, p_test, 0.17, "global", pstar)
    exposure_t = policy.tier_exposure(test, p_test, 0.17, "per-tier", pstar)
    sensitivity = policy.conversion_sensitivity(
        test, p_test, cm, ctx["prepaid"], ann, 0.17)
    gradient = policy.protection_gradient(test)

    at17 = cost[cost["volume_flagged"] == 0.17].iloc[0]
    t3_g = exposure_g.set_index("geo_tier").loc["TIER3"]
    t3_t = exposure_t.set_index("geo_tier").loc["TIER3"]
    metro_t = exposure_t.set_index("geo_tier").loc["METRO"]
    worst_ratio = max(r for r in audit_tiered["ratio"] if isinstance(r, (int, float)))
    fa01 = "PASS" if (audit_tiered["verdict"] == "PASS").all() else "FAIL"

